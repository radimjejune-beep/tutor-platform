export default function Help() {
  const { user } = useAuth();
  const list = user.role === 'tutor' ? TUTOR : CLIENT;
  const [open, setOpen] = useState(list[0].id);
  return (
    <>
      <div className="page-head">
        <div>
          <h1 className="page-title">Как пользоваться</h1>
          <div className="lead">Коротко о каждом разделе. Нажмите на тему, чтобы раскрыть.</div>
        </div>
      </div>
      <div className="help-list">
        {list.map((s) => (
          <section key={s.id} className={`panel help-item${open === s.id ? ' open' : ''}`}>
            <button type="button" className="help-head" aria-expanded={open === s.id} onClick={() => setOpen(open === s.id ? null : s.id)}>
              <Icon name={s.icon} size={20} />
              <span>{s.title}</span>
              <span className="help-chev"><Icon name="back" size={16} /></span>
            </button>
            {open === s.id && (
              <div className="help-body">
                <ol>{s.steps.map((t) => <li key={t}>{t}</li>)}</ol>
                <div className="row" style={{ gap: 8, flexWrap: 'wrap' }}>
                  {s.links.map(([to, label]) => <Link key={to} to={to} className="btn btn-secondary btn-sm">{label}</Link>)}
                </div>
              </div>
            )}
          </section>
        ))}
      </div>
    </>
  );
}
