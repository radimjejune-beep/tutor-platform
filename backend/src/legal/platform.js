function owner() {
  const env = process.env;
  return {
    name: env['PLATFORM_OWNER_NAME'] || '',
    inn: env['PLATFORM_OWNER_INN'] || '',
    email: env['PLATFORM_EMAIL'] || '',
    site: (env['PLATFORM_SITE'] || env['FRONTEND_URL'] || '').replace(/\/+$/, ''),
  };
}
const configured = () => { const o = owner(); return Boolean(o.name && o.inn && o.email); };

function fill(text) {
  const o = owner();
  return text
    .replaceAll('{NAME}', o.name || '[ФИО владельца не указано]')
    .replaceAll('{INN}', o.inn || '[ИНН не указан]')
    .replaceAll('{EMAIL}', o.email || '[почта не указана]')
    .replaceAll('{SITE}', o.site || '[адрес сайта не указан]')
    .replaceAll('{DATE}', EDITION_DATE);
}

